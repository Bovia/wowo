// Local coords: x across the piece, z away from the wall it backs onto, y up from the floor.
export type LBox = [x0: number, y0: number, z0: number, x1: number, y1: number, z1: number, color: string];
export type Rect = [x0: number, z0: number, x1: number, z1: number];

export type Piece = {
  w: number;
  d: number;
  prefer: "center" | "corner";
  boxes: LBox[];
  solids?: Rect[];
};

const pick = (colors: string[], i: number) => colors[((i % colors.length) + colors.length) % colors.length];

function legs(x0: number, z0: number, x1: number, z1: number, h: number, s: number, color: string): LBox[] {
  return [
    [x0, 0, z0, x0 + s, h, z0 + s, color],
    [x1 - s, 0, z0, x1, h, z0 + s, color],
    [x0, 0, z1 - s, x0 + s, h, z1, color],
    [x1 - s, 0, z1 - s, x1, h, z1, color],
  ];
}

function quilt(x0: number, z0: number, x1: number, z1: number, y0: number, y1: number): LBox[] {
  const colors = ["#e88f8f", "#f2b3a6", "#e27d7f", "#f6c8b6"];
  const out: LBox[] = [];
  const nx = 8;
  const nz = 6;
  for (let i = 0; i < nx; i++)
    for (let j = 0; j < nz; j++)
      out.push([
        x0 + ((x1 - x0) * i) / nx,
        y0,
        z0 + ((z1 - z0) * j) / nz,
        x0 + ((x1 - x0) * (i + 1)) / nx,
        y1,
        z0 + ((z1 - z0) * (j + 1)) / nz,
        pick(colors, i * 3 + j * 5 + ((i + j) % 2)),
      ]);
  return out;
}

